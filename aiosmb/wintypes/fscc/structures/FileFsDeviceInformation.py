import enum
import io

from aiosmb.wintypes.fscc.structures._helpers import as_int, read_exact


class DeviceType(enum.Enum):
	FILE_DEVICE_CD_ROM = 0x00000002
	FILE_DEVICE_DISK = 0x00000007
	FILE_DEVICE_DISK_FILE_SYSTEM = 0x00000008
	FILE_DEVICE_NAMED_PIPE = 0x00000011
	FILE_DEVICE_NETWORK_FILE_SYSTEM = 0x00000014


class DeviceCharacteristics(enum.IntFlag):
	NONE = 0x00000000
	FILE_REMOVABLE_MEDIA = 0x00000001
	FILE_READ_ONLY_DEVICE = 0x00000002
	FILE_FLOPPY_DISKETTE = 0x00000004
	FILE_WRITE_ONCE_MEDIA = 0x00000008
	FILE_REMOTE_DEVICE = 0x00000010
	FILE_DEVICE_IS_MOUNTED = 0x00000020
	FILE_VIRTUAL_VOLUME = 0x00000040
	FILE_AUTOGENERATED_DEVICE_NAME = 0x00000080
	FILE_DEVICE_SECURE_OPEN = 0x00000100
	FILE_CHARACTERISTIC_PNP_DEVICE = 0x00000800
	FILE_CHARACTERISTIC_TS_DEVICE = 0x00001000
	FILE_CHARACTERISTIC_WEBDAV_DEVICE = 0x00002000


class FileFsDeviceInformation:
	def __init__(self):
		self.DeviceType = DeviceType.FILE_DEVICE_DISK
		self.Characteristics = DeviceCharacteristics.NONE

	def to_bytes(self):
		return (
			as_int(self.DeviceType).to_bytes(4, 'little')
			+ as_int(self.Characteristics).to_bytes(4, 'little')
		)

	@staticmethod
	def from_bytes(data):
		return FileFsDeviceInformation.from_buffer(io.BytesIO(data))

	@staticmethod
	def from_buffer(buff):
		data = read_exact(buff, 8, 'FILE_FS_DEVICE_INFORMATION')
		msg = FileFsDeviceInformation()
		device_type = int.from_bytes(data[0:4], 'little')
		try:
			msg.DeviceType = DeviceType(device_type)
		except ValueError:
			msg.DeviceType = device_type
		msg.Characteristics = DeviceCharacteristics(
			int.from_bytes(data[4:8], 'little')
		)
		return msg
